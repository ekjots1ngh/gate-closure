"""Write docs/RESULTS.md and the README figures from data/out/results.json.

Every number in the docs is rendered here from the pipeline's own output, so the write-up
cannot drift from the code. Run: python -m gclose.report
"""

from __future__ import annotations

import json

from . import DOCS, figures
from .decide import RESULTS

FORECASTERS = {
    "schedule": "no forecast, fixed schedule",
    "ours": "ours, logistic",
    "boosted": "boosted classifier",
    "persistence_cal": "calibrated persistence",
    "indicated": "NESO indicated imbalance",
    "side_oracle": "knowing the side an hour early",
}
PRICE_POLICIES = {
    "price/ridge": "price forecast, ridge",
    "price/boosted": "price forecast, boosted",
    "price/last_seen": "last price seen",
    "price/oracle": "knowing the price an hour early",
    "hindsight": "perfect hindsight, every price known",
}
MODELS = {
    "coin": "coin (long-run share short)",
    "persistence_raw": "persistence, raw 0/1",
    "persistence_cal": "persistence, calibrated",
    "indicated": "NESO indicated imbalance",
    "ours": "ours",
}
YEAR_COLUMNS = {
    "chain/schedule": "schedule",
    "chain/ours": "ours (chain)",
    "chain/persistence_cal": "persistence (chain)",
    "chain/indicated": "NESO (chain)",
    "chain/side_oracle": "knowing the side",
    "hindsight": "hindsight",
}


def _table(header: list[str], rows: list[list[str]]) -> str:
    """A GitHub markdown table: first column left-aligned, the rest right-aligned."""
    lines = [header, [":---"] + ["---:"] * (len(header) - 1), *rows]
    return "\n".join("| " + " | ".join(line) + " |" for line in lines)


def _with_interval(e: dict, fmt: str = "{:.1f}", scale: float = 1.0) -> str:
    value, lo, hi = (scale * e[key] for key in ("value", "lo", "hi"))
    return f"{fmt.format(value)} [{fmt.format(lo)}, {fmt.format(hi)}]"


def render(results: dict) -> str:
    money = results["money"]

    def cell(policy: str) -> str:
        return _with_interval(money[policy]) if policy in money else ""

    forecast_rows = [
        [
            MODELS[s["model"]],
            _with_interval(s["brier"], "{:.4f}"),
            f"{s['log_loss']:.4f}",
            "" if s["model"] == "ours" else _with_interval(s["ours_minus"], "{:+.4f}"),
        ]
        for s in results["forecasts"]
    ]
    money_rows = [[label, cell(f"one/{name}"), cell(f"chain/{name}")] for name, label in FORECASTERS.items()]
    price_rows = [[label, cell(policy)] for policy, label in PRICE_POLICIES.items()]

    gain_rows = []
    for policy, gain in results["gain"].items():
        family, name = policy.split("/")
        gain_rows.append(
            [
                f"{FORECASTERS[name]} ({'chain' if family == 'chain' else 'one step'})",
                _with_interval(gain["gbp"], "{:+.2f}"),
                _with_interval(gain["share"], "{:.1f}", scale=100) + "%",
                _with_interval(results["gain_without_spike_half_hours"][policy]["gbp"], "{:+.2f}"),
                _with_interval(results["gain_without_top_days"][policy]["gbp"], "{:+.2f}"),
            ]
        )

    era_rows = [
        [
            era,
            _with_interval(e["ours_minus_persistence_cal"], "{:+.4f}"),
            f"{e['chain_ours']:.1f}",
            f"{e['schedule']:.1f}",
            _with_interval(e["gain"]["gbp"], "{:+.2f}"),
        ]
        for era, e in results["by_era"].items()
    ]
    year_rows = [[str(y["year"]), *(f"{y[policy]:.1f}" for policy in YEAR_COLUMNS)] for y in results["by_year"]]
    skill = results["value_of_skill"]
    skill_rows = [
        [f"{one['k']:.2f}", f"{one['brier']:.4f}", f"{one['gbp']:.1f}", f"{chain['gbp']:.1f}"]
        for one, chain in zip(skill["one"], skill["chain"], strict=True)
    ]

    return f"""# Results

Generated by `python -m gclose.report` from `data/out/results.json`; do not edit by hand.
Walk-forward test, July 2022 to June 2026, refitted monthly; 70,120 half hours. Intervals are 90%,
resampling whole calendar weeks (1,000 resamples); differences are resampled in pairs.

## Forecasts of P(short)

Lower is better for both scores. The last column is ours minus each model, so negative means ours is better.

{_table(["model", "Brier [90% CI]", "log loss", "ours minus model, Brier"], forecast_rows)}

## Money: a 1 MW / 2 MWh battery, £ per day

One step: the forecast prices the next half hour only. Chain: it also shapes the next few half hours,
fading at the side's own persistence.

{_table(["forecast", "one step [90% CI]", "chain [90% CI]"], money_rows)}

Price forecasts (one step) and the two ceilings:

{_table(["policy", "£ per day [90% CI]"], price_rows)}

## Gain over the fixed schedule, £ per day

"Share" is the share of the gap between the schedule and knowing the side an hour early. The protocol's
spike check leaves out the top 1% of half hours by absolute price; the harsher check leaves out the top 1% of days.

{_table(["forecast", "gain [90% CI]", "share of gap", "without spike half hours", "without top 1% of days"], gain_rows)}

## By era

Until February 2024 the stored prices are first prints; after it, Elexon's next-day revisions (PROTOCOL.md amendment 4).

{_table(["era", "ours minus calibrated persistence, Brier", "chain ours", "schedule", "gain"], era_rows)}

## By year, £ per day

{_table(["year", *YEAR_COLUMNS.values()], year_rows)}

## Value of skill

Our forecast errors scaled by k: k = 0 knows the side, k = 1 is our forecast, k above 1 is worse.

{_table(["k", "Brier", "one step, £/day", "chain, £/day"], skill_rows)}

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="value_of_skill_dark.svg">
  <img alt="Money per day against Brier score" src="value_of_skill_light.svg">
</picture>
"""


def main() -> None:
    results = json.loads(RESULTS.read_text())
    figures.write_all(results)
    (DOCS / "RESULTS.md").write_text(render(results))
    print(f"wrote {DOCS / 'RESULTS.md'} and the figures")


if __name__ == "__main__":
    main()
